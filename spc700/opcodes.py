def bit_index(opcode: int) -> int:
    return opcode >> 5


def call_index(opcode: int) -> int:
    return opcode >> 4


def _signed(value: int) -> int:
    return value - 0x100 if value >= 0x80 else value


def _fields(data: bytes | bytearray, offset: int, address: int, p: int) -> dict[str, str]:
    first = data[offset + 1] if offset + 1 < len(data) else 0
    second = data[offset + 2] if offset + 2 < len(data) else 0
    absolute = first | (second << 8)
    return {
        "op0": f"{first:02x}",
        "op1": f"{second:02x}",
        "dp0": f"{(p << 8) | first:03x}",
        "dp1": f"{(p << 8) | second:03x}",
        "abs": f"{absolute:04x}",
        "mem": f"{absolute & 0x1FFF:04x}",
        "bit": f"{absolute >> 13:d}",
        "rel2": f"{(address + 2 + _signed(first)) & 0xFFFF:04x}",
        "rel3": f"{(address + 3 + _signed(second)) & 0xFFFF:04x}",
    }


def decode(data: bytes | bytearray, offset: int, address: int, p: int = 0) -> Instruction:
    if offset >= len(data):
        raise Truncated(f"offset {offset} is past the end of {len(data)} bytes")
    opcode = data[offset]
    mnemonic, mode, size = OPCODES[opcode]
    if offset + size > len(data):
        raise Truncated(
            f"opcode {opcode:02X} at {offset} needs {size} bytes, {len(data) - offset} remain"
        )
    return Instruction(
        address=address,
        size=size,
        text=TEXT[opcode].format(**_fields(data, offset, address, p)),
        opcode=opcode,
        mnemonic=mnemonic,
        mode=mode,
    )


def disassemble(
    data: bytes | bytearray,
    offset: int,
    address: int,
    count: int | None = None,
    p: int = 0,
    stop_at_return: bool = False,
) -> list[Instruction]:
    listing: list[Instruction] = []
    while count is None or len(listing) < count:
        try:
            instruction = decode(data, offset, address, p)
        except Truncated:
            break
        listing.append(instruction)
        offset += instruction.size
        address = (address + instruction.size) & 0xFFFF
        if stop_at_return and instruction.mnemonic in RETURNS:
            break
    return listing
